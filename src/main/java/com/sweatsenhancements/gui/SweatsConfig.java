    private interface ToggleVisitor {
        void visit(Field field, Object holder, Feature feature);
    }

    /** Walks the category fields, handing every switch that has a matching feature to the visitor. */
    private void forEachToggle(ToggleVisitor visitor) {
        try {
            for (Field category : getClass().getFields()) {
                Object holder = category.get(this);
                if (holder == null) continue;
                for (Field option : holder.getClass().getFields()) {
                    if (option.getType() != boolean.class) continue;
                    Feature feature = Features.byId(option.getName());
                    if (feature == null) continue;
                    visitor.visit(option, holder, feature);
                }
            }
        } catch (Throwable t) {
            System.out.println("[SweatsEnhancements] config sync failed: " + t);
        }
    }
